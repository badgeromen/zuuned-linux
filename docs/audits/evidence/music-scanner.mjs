import {mkdtempSync, mkdirSync, writeFileSync, statSync, utimesSync, readFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join, dirname} from 'node:path';
import {spawnSync} from 'node:child_process';
const scratch=mkdtempSync(join(tmpdir(),'zuuned-parser-audit-'));
const music=join(scratch,'music'), db=join(scratch,'library.db');
mkdirSync(music);
const run=(cmd,args)=>{const r=spawnSync(cmd,args,{encoding:'utf8',env:{...process.env,XDG_CACHE_HOME:join(scratch,'cache'),XDG_CONFIG_HOME:join(scratch,'config'),XDG_DATA_HOME:join(scratch,'data')}});if(r.status!==0) throw new Error(`${cmd}: ${r.stderr}`);return r.stdout;};
const audio=(path,tags={})=>{const p=join(music,path);mkdirSync(dirname(p),{recursive:true});run('ffmpeg',['-hide_banner','-loglevel','error','-f','lavfi','-i','anullsrc=r=48000:cl=stereo','-t','0.15',...Object.entries(tags).flatMap(([k,v])=>['-metadata',`${k}=${v}`]),'-y',p]);return p;};
const base={artist:'Tagged Artist',album_artist:'Tagged Owner',title:'Tagged Title',album:'Tagged Album',date:'2021',track:'2',genre:'Pop'};
audio('Downloads/21/owner.flac',{artist:'Adele',title:'Set Fire to the Rain',album:'21',date:'2011',track:'5'});
audio('A/World 2/title.flac',{...base,album:'World 2'});
for(const disc of [1,2]) for(const track of [1,2]) audio(`Discs/Double/CD${disc}/${track}.flac`,{...base,artist:'Disc Artist',album_artist:'Disc Artist',album:`Double (CD ${disc})`,title:`${disc===1?'Z':'A'} disc${disc} track${track}`,track:String(track),disc:String(disc)});
audio('Codec/Ogg/file.ogg',base);
audio('Codec/Opus/file.opus',base);
audio('Trim/Album/space.flac',{...base,artist:'Spaced Artist ',album_artist:'Spaced Artist '});
audio('Trim/Album/blank.flac',{...base,artist:' ',album_artist:' ',title:' '});
audio('Case/Album/upper.flac',{...base,album_artist:'CASE Artist'});
audio('Case/Album/lower.flac',{...base,album_artist:'Case Artist'});
audio('01 - Adele - Hello.flac');
const repair=audio('Folder Owner/Folder Album/probe.flac',{...base,artist:'Original Artist',album_artist:'Original Owner',title:'Original Title'});
const skip=audio('Stat/Album/stat.flac',{...base,title:'Before Retag'});
const scan=()=>run('./build/librarytool',['scan',music,db]);
const query=(sql)=>JSON.parse(run('sqlite3',['-json','-readonly',db,sql]));
scan();
const initial=query('SELECT filepath,title,artist,albumartist,album,year,tracknumber,duration FROM tracks ORDER BY albumartist COLLATE NOCASE,album COLLATE NOCASE,tracknumber,title COLLATE NOCASE;').map(r=>({...r,filepath:r.filepath.replace(music+'/','')}));
const probeBefore=statSync(repair);
writeFileSync(repair,'unreadable partial audio');
utimesSync(repair,new Date(),new Date(probeBefore.mtimeMs+2000));
const statBefore=statSync(skip);
audio('Stat/Album/stat.flac',{...base,title:'After Retag Longer Title'});
utimesSync(skip,statBefore.atime,statBefore.mtime);
scan();
const after=query("SELECT filepath,title,artist,albumartist,album,year,tracknumber,duration FROM tracks WHERE filepath LIKE '%probe.flac' OR filepath LIKE '%stat.flac';").map(r=>({...r,filepath:r.filepath.replace(music+'/','')}));
const result={scratch,initial,after,oggProbe:JSON.parse(run('ffprobe',['-v','error','-show_entries','format_tags:stream_tags','-of','json',join(music,'Codec/Ogg/file.ogg')]))};
writeFileSync('/tmp/zuuned-music-audit-fixture-results.json',JSON.stringify(result,null,2));
console.log(JSON.stringify(result,null,2));
